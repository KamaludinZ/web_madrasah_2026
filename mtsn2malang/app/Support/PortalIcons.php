    /** Path SVG untuk nama ikon; nama tak dikenal jatuh ke ikon DEFAULT. */
    public static function path(?string $name): string
    {
        return (self::ICONS[$name] ?? self::ICONS[self::DEFAULT])[1];
    }

    /** Opsi untuk Select Filament: nama => label. */
    public static function options(): array
    {
        return array_map(fn (array $icon) => $icon[0], self::ICONS);
    }

    public static function names(): array
    {
        return array_keys(self::ICONS);
    }

    /** SVG ikon sebagai HTML (untuk panel admin). Nama & path berasal dari daftar tetap di atas. */
    public static function svg(?string $name, string $class = 'w-5 h-5'): string
    {
        return '<svg class="' . e($class) . '" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true">'
            . '<path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="' . e(self::path($name)) . '"/></svg>';
    }

    /**
     * Opsi Select Filament dengan pratinjau ikon (pakai ->allowHtml()).
     * Label di-escape; SVG dibangun dari daftar tetap, jadi aman dirender.
     */
    public static function htmlOptions(): array
    {
        $options = [];
        foreach (self::ICONS as $name => [$label]) {
            $options[$name] = '<span class="flex items-center gap-2">'
                . self::svg($name, 'w-5 h-5 shrink-0 text-primary-600')
                . '<span>' . e($label) . '</span></span>';
        }

        return $options;
    }
